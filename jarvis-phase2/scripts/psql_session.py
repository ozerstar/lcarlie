"""Operator test harness: one long-lived psql session over a pipe.

Needed because no psycopg driver is installed on the production host and
Phase 2C requires transaction-safe (BEGIN ... ROLLBACK) adversarial and state
tests. A single session is what keeps the whole test inside one transaction.

SCOPE: test harness only. It is never imported by the Jarvis runtime and it
never receives model- or user-supplied text -- every literal it encodes is
generated by the test itself.
"""
from __future__ import annotations

import json
import subprocess
import time
from typing import Any

SENTINEL = "<<<EOQ>>>"
STATUS_MARK = "<<<STAT>>>"
MESSAGE_MARK = "<<<MSG>>>"
# Field separator: a control character that cannot occur inside the JSON
# payloads we round-trip, so splitting a row can never corrupt state_json.
FIELD_SEP = "\x01"


class PsqlError(RuntimeError):
    pass


def encode(value: Any) -> str:
    """Encode a test-generated literal. Not a general-purpose quoter."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, (dict, list)):
        value = json.dumps(value, sort_keys=True, separators=(",", ":"))
    if not isinstance(value, str):
        raise TypeError(f"unsupported literal type: {type(value).__name__}")
    return "'" + value.replace("'", "''") + "'"


class PsqlSession:
    def __init__(self, container: str = "lcarlie-postgres", user: str = "n8n", db: str = "n8n"):
        self.proc = subprocess.Popen(
            ["docker", "exec", "-i", container, "psql", "-X", "-q", "-At",
             "-F", FIELD_SEP, "-U", user, "-d", db,
             "-v", "ON_ERROR_STOP=0", "-f", "-"],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            # stderr is DISCARDED on purpose. psql writes diagnostics to
            # stderr unbuffered while its stdout through a pipe is block
            # buffered, so an ERROR line can arrive *after* our stdout
            # sentinel and be misattributed to the next statement. Error
            # state is therefore read in-band from psql's own :ERROR /
            # :SQLSTATE / :LAST_ERROR_MESSAGE variables instead.
            stderr=subprocess.DEVNULL, text=True,
        )
        self._closed = False

    # -- low level ---------------------------------------------------------
    def run(self, sql: str, timeout: float = 30.0) -> list[str]:
        """Execute one statement. Raises PsqlError if the server rejected it."""
        if self._closed:
            raise PsqlError("session already closed")
        self.proc.stdin.write(sql.strip().rstrip(";") + ";\n")
        self.proc.stdin.write(f"\\echo {STATUS_MARK} :ERROR :SQLSTATE\n")
        self.proc.stdin.write(f"\\echo {MESSAGE_MARK}\n")
        self.proc.stdin.write("\\echo :LAST_ERROR_MESSAGE\n")
        self.proc.stdin.write(f"\\echo {SENTINEL}\n")
        self.proc.stdin.flush()

        rows: list[str] = []
        message: list[str] = []
        failed, sqlstate, section = False, "", "rows"
        deadline = time.time() + timeout
        while time.time() < deadline:
            line = self.proc.stdout.readline()
            if line == "":
                raise PsqlError("psql closed stdout unexpectedly")
            line = line.rstrip("\n")
            if line == SENTINEL:
                if failed:
                    detail = " ".join(part for part in message if part).strip()
                    raise PsqlError(f"[{sqlstate}] {detail}" if detail else f"[{sqlstate}]")
                return rows
            if line.startswith(STATUS_MARK):
                parts = line[len(STATUS_MARK):].split()
                failed = bool(parts) and parts[0].casefold() == "true"
                sqlstate = parts[1] if len(parts) > 1 else ""
                section = "gap"
            elif line == MESSAGE_MARK:
                section = "message"
            elif section == "rows":
                rows.append(line)
            elif section == "message":
                message.append(line)
        raise PsqlError(f"timeout after {timeout}s waiting for: {sql[:80]}")

    def fetch_one(self, sql: str, params: tuple[Any, ...] = ()) -> tuple[Any, ...] | None:
        """psycopg-compatible shim: substitutes %s with encoded literals."""
        rendered = sql
        for param in params:
            rendered = rendered.replace("%s", encode(param), 1)
        rows = self.run(rendered)
        if not rows:
            return None
        return tuple(self._coerce(part) for part in rows[0].split(FIELD_SEP))

    @staticmethod
    def _coerce(text: str) -> Any:
        if text.startswith("{") or text.startswith("["):
            try:
                return json.loads(text)
            except ValueError:
                return text
        if text.lstrip("-").isdigit():
            return int(text)
        return text

    # -- helpers -----------------------------------------------------------
    def scalar(self, sql: str) -> Any:
        row = self.fetch_one(sql)
        return None if row is None else row[0]

    def expect_denied(self, sql: str) -> tuple[bool, str]:
        """Run a statement that MUST be rejected. Returns (denied, detail)."""
        self.run("SAVEPOINT adversarial")
        try:
            self.run(sql)
        except PsqlError as exc:
            self.run("ROLLBACK TO SAVEPOINT adversarial")
            return True, str(exc)
        self.run("ROLLBACK TO SAVEPOINT adversarial")
        return False, "statement was ACCEPTED (expected denial)"

    def close(self) -> None:
        if self._closed:
            return
        self._closed = True
        try:
            self.proc.stdin.write("\\q\n")
            self.proc.stdin.flush()
        except Exception:  # noqa: BLE001 - elle kosturulan betik; hata ekranda gorunur
            pass
        try:
            self.proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            self.proc.kill()

    def __enter__(self) -> "PsqlSession":
        return self

    def __exit__(self, *exc_info) -> None:
        self.close()
