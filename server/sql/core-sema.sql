-- -----------------------------------------------------------------------------
-- core.telefon_e164(text) -> E.164 veya NULL
--
-- 🔴 GECERSIZ NUMARA ASLA 'DUZELTILMEZ', NULL DONER.
--    CR-001 olcumu: 37 siparisten birinde 9 haneli telefon var. Eksik haneyi
--    tahmin etmek (basa 5 koymak gibi) YANLIS bir musteriyle eslesme uretir.
--    Normalize edilemeyen numara INVALID isaretlenir ve eslestirmede
--    KULLANILMAZ - ham hali her zaman saklanir.
--
-- Kabul edilen girdiler (Turkiye):
--   +90 5xx xxx xx xx / 90xxxxxxxxxx / 0xxxxxxxxxx / 5xxxxxxxxx
-- Ulusal numara 10 hane olmali ve 2-5 arasi bir rakamla baslamali
-- (5=mobil, 2/3/4=sabit hat).
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION core.telefon_e164(p_ham text)
RETURNS text
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
  d text;
  ulusal text;
BEGIN
  IF p_ham IS NULL THEN RETURN NULL; END IF;
  d := regexp_replace(p_ham, '\D', '', 'g');
  IF d = '' THEN RETURN NULL; END IF;

  IF length(d) = 12 AND left(d,2) = '90' THEN
    ulusal := right(d,10);
  ELSIF length(d) = 11 AND left(d,1) = '0' THEN
    ulusal := right(d,10);
  ELSIF length(d) = 10 THEN
    ulusal := d;
  ELSIF length(d) = 13 AND left(d,3) = '090' THEN
    ulusal := right(d,10);
  ELSE
    -- 9 haneli, 14+ haneli, yurt disi vb. -> normalize EDILMEZ
    RETURN NULL;
  END IF;

  -- Ulusal numara 2-5 ile baslamali; 0/1/6/7/8/9 ile baslayan gecersizdir.
  IF left(ulusal,1) NOT IN ('2','3','4','5') THEN
    RETURN NULL;
  END IF;

  RETURN '+90' || ulusal;
END;
$$;

COMMENT ON FUNCTION core.telefon_e164(text) IS
  'TR telefonunu E.164''e cevirir. Normalize edilemezse NULL - ASLA tahmin etmez.';

-- -----------------------------------------------------------------------------
-- core.eposta_normal(text) -> kucuk harf, kirpilmis veya NULL
--
-- 🔴 Turkce yerel ayarda lower() 'I' harfini beklenmedik cevirebilir; e-posta
--    ASCII oldugu icin once ASCII disi karakter kontrolu yapilir.
-- 🔴 Gmail nokta/artı normalizasyonu YAPILMAZ: 'a.b@gmail.com' ile
--    'ab@gmail.com' teknik olarak ayni kutu olabilir ama bu bir SAGLAYICI
--    kuralidir, evrensel degil. Agresif normalizasyon YANLIS BIRLESTIRME
--    uretir; birlestirme geri alinamaz. Muhafazakar taraf secildi.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION core.eposta_normal(p_ham text)
RETURNS text
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE e text;
BEGIN
  IF p_ham IS NULL THEN RETURN NULL; END IF;
  e := btrim(p_ham);
  IF e = '' THEN RETURN NULL; END IF;
  e := lower(e);
  -- en az bir '@' ve noktali alan adi
  IF e !~ '^[^@[:space:]]+@[^@[:space:]]+\.[a-z]{2,}$' THEN
    RETURN NULL;
  END IF;
  RETURN e;
END;
$$;

COMMENT ON FUNCTION core.eposta_normal(text) IS
  'E-postayi kucuk harfe cevirip dogrular. Gecersizse NULL. Nokta/arti normalizasyonu YAPMAZ.';

-- =============================================================================
-- 2) KANONIK MUSTERI
-- =============================================================================
CREATE TABLE IF NOT EXISTS core.customer (
  customer_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Gosterim/arama kolayligi icin birincil degerler; OTORITE DEGIL,
  -- customer_identity tablosundan TURETILMISTIR.
  phone_normalized  text,
  email_normalized  text,
  identity_status   text NOT NULL DEFAULT 'UNKNOWN'
                    CHECK (identity_status IN ('MATCHED','CONFLICT','INVALID','UNKNOWN')),
  match_method      text,
  match_confidence  smallint CHECK (match_confidence BETWEEN 0 AND 100),
  notlar            jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE core.customer IS
  'Kanonik musteri. phone/email kolonlari TURETILMIS gosterim degerleridir; otorite customer_identity''dir.';
COMMENT ON COLUMN core.customer.identity_status IS
  'MATCHED=tek musteriye baglandi · CONFLICT=cakisma var, BIRLESTIRILMEDI · INVALID=normalize edilemedi · UNKNOWN=atfedilemedi';

CREATE INDEX IF NOT EXISTS customer_phone_idx  ON core.customer (phone_normalized) WHERE phone_normalized IS NOT NULL;
CREATE INDEX IF NOT EXISTS customer_email_idx  ON core.customer (email_normalized) WHERE email_normalized IS NOT NULL;
CREATE INDEX IF NOT EXISTS customer_status_idx ON core.customer (identity_status);

-- =============================================================================
-- 3) KIMLIK KAYITLARI
-- =============================================================================
CREATE TABLE IF NOT EXISTS core.customer_identity (
  identity_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id        bigint NOT NULL REFERENCES core.customer(customer_id) ON DELETE RESTRICT,

  kaynak             text NOT NULL,   -- wix | whatsapp | instagram | messenger | web | manual
  kimlik_tipi        text NOT NULL
                     CHECK (kimlik_tipi IN ('phone','email','wix_buyer_id','wa_id','ig_id','psid','web_id')),

  -- 🔴 HAM DEGER ASLA KAYBOLMAZ. Normalize edilmis deger AYRI kolonda.
  --    Normalizasyon kurali degisirse ham degerden yeniden turetilebilir.
  source_customer_id text,            -- kaynak sistemdeki musteri kaydinin kimligi
  deger_ham          text NOT NULL,
  deger_normal       text,            -- normalize edilemezse NULL
  gecerli            boolean NOT NULL DEFAULT true,

  match_method       text NOT NULL,   -- phone_e164 | email | wix_buyer_id | source_id | manual
  match_confidence   smallint NOT NULL CHECK (match_confidence BETWEEN 0 AND 100),
  match_reason       text,            -- insan okuyacak gerekce

  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now()
);

-- 🔴 IDEMPOTENCY ANAHTARI.
--    Ayni kaynaktan ayni ham deger ayni kaynak-musteri icin TEK kayit.
--    'source_customer_id' anahtara DAHIL: ayni telefon iki farkli Wix
--    alicisinda gorunuyorsa IKI SATIR olusur - cakismanin kaniti budur.
--    Anahtarda olmasaydi ikinci kayit birinciyi EZER ve cakisma kaybolurdu.
CREATE UNIQUE INDEX IF NOT EXISTS customer_identity_tekil
  ON core.customer_identity (kaynak, kimlik_tipi, deger_ham, COALESCE(source_customer_id,''));

CREATE INDEX IF NOT EXISTS customer_identity_normal_idx
  ON core.customer_identity (kimlik_tipi, deger_normal) WHERE deger_normal IS NOT NULL;
CREATE INDEX IF NOT EXISTS customer_identity_musteri_idx
  ON core.customer_identity (customer_id);

COMMENT ON TABLE core.customer_identity IS
  'Bir musterinin bilinen tum kimlikleri. deger_ham ASLA silinmez/degistirilmez.';

-- =============================================================================
-- 4) KIMLIK CAKISMALARI
-- =============================================================================
-- 🔴 CAKISMA BIR HATA DEGIL, BIR OLGUDUR - kaydedilir, otomatik COZULMEZ.
--    CR-001 olcumu: 37 siparisten birinde AYNI TELEFON iki farkli Wix
--    alicisina bagli. Bunlari otomatik birlestirmek iki ayri kisiyi tek
--    musteri yapabilir ve BU GERI ALINAMAZ. Insan karari beklenir.
CREATE TABLE IF NOT EXISTS core.identity_conflict (
  conflict_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kimlik_tipi     text NOT NULL,
  deger_normal    text NOT NULL,
  customer_ids    bigint[] NOT NULL,
  kaynak_kayitlar jsonb NOT NULL DEFAULT '[]'::jsonb,  -- {kaynak, source_customer_id, deger_ham}
  durum           text NOT NULL DEFAULT 'ACIK'
                  CHECK (durum IN ('ACIK','COZULDU','YOKSAYILDI')),
  cozum_notu      text,
  tespit_at       timestamptz NOT NULL DEFAULT now(),
  cozum_at        timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS identity_conflict_tekil
  ON core.identity_conflict (kimlik_tipi, deger_normal) WHERE durum = 'ACIK';

COMMENT ON TABLE core.identity_conflict IS
  'Ayni normalize deger birden fazla musteriye baglaninca acilir. OTOMATIK BIRLESTIRME YOK.';

-- =============================================================================
-- 5) SOURCE AUTHORITY MAP  (makine okunur)
-- =============================================================================
CREATE TABLE IF NOT EXISTS core.source_authority (
  alan                text PRIMARY KEY,
  authority           text NOT NULL,
  mirror              text,
  freshness           text,
  current_connection  text NOT NULL
                      CHECK (current_connection IN
                        ('CONNECTED','PARTIAL','SOURCE_NOT_CONNECTED','NONE','UNKNOWN')),
  gap                 text,
  dogrulama_zamani    timestamptz,
  dogrulama_yontemi   text,
  notlar              text
);

COMMENT ON TABLE core.source_authority IS
  'Hangi alanin otoritesi HANGI DIS SISTEM. Postgres yalnizca ayna - bu tablo onu hatirlatmak icin var.';

