BEGIN;

CREATE TABLE IF NOT EXISTS core.pazar_bulgu (
  bulgu_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kod         text NOT NULL,
  seviye      text NOT NULL,
  bulgu       text NOT NULL,
  kaynak      text NOT NULL,
  tarih       text NOT NULL,
  yorum       text,
  kaydeden    text NOT NULL DEFAULT current_user,
  olusturma   timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT pazar_bulgu_seviye_check CHECK (
    seviye IN ('FACT','INTERPRETATION','HYPOTHESIS','NOT_CONNECTED')),
  -- Kaynaksiz bulgu kaydedilemez.
  CONSTRAINT pazar_bulgu_kaynak_dolu CHECK (length(btrim(kaynak)) >= 3),
  CONSTRAINT pazar_bulgu_metin_dolu  CHECK (length(btrim(bulgu))  >= 8)
);

CREATE INDEX IF NOT EXISTS pazar_bulgu_kod_idx ON core.pazar_bulgu (kod, olusturma DESC);

-- --------------------------------------------------------------------------
-- MEVCUT 5 SATIRI TASI -- elle yeniden yazmadan, gorunumun KENDISINDEN.
-- Elle kopyalamak bir harf degistirse kayit sessizce bozulurdu.
-- Tekrar calistirmaya karsi korumali: tablo doluysa hic dokunmaz.
-- --------------------------------------------------------------------------
INSERT INTO core.pazar_bulgu (kod, seviye, bulgu, kaynak, tarih, yorum, kaydeden)
SELECT kod, seviye, bulgu, kaynak, tarih, yorum, 'MIGRASYON_20260920'
  FROM mart.pazar_arastirma
 WHERE NOT EXISTS (SELECT 1 FROM core.pazar_bulgu);

DROP VIEW IF EXISTS mart.pazar_arastirma CASCADE;

CREATE VIEW mart.pazar_arastirma AS
SELECT kod, seviye, bulgu, kaynak, tarih, yorum, kaydeden, olusturma
  FROM core.pazar_bulgu
 ORDER BY olusturma DESC;

